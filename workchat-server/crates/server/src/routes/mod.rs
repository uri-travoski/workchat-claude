pub mod account;
pub mod admin;
pub mod adminview;
pub mod auto;
pub mod avatars;
pub mod botadmin;
pub mod botapi;
pub mod chat;
pub mod files;
pub mod org;
pub mod search;
pub mod social;
pub mod ws;

use crate::state::St;
use axum::routing::{delete, get, patch, post, put};
use axum::Router;

pub fn api_router() -> Router<St> {
    use account::*;
    Router::new()
        .route("/health", get(health))
        .route("/meta", get(meta))
        .route("/setup", post(setup))
        .route("/login", post(login))
        .route("/login/link", post(login_link))
        .route("/refresh", post(refresh))
        .route("/logout", post(logout))
        .route("/me", get(get_me).patch(update_me))
        .route("/me/password", post(change_password))
        .route("/sessions", get(list_sessions))
        .route("/sessions/revoke-others", post(revoke_other_sessions))
        .route("/sessions/revoke-all", post(revoke_all_sessions))
        .route("/sessions/{id}", delete(revoke_session))
        .route("/users", get(chat::list_users))
        .route("/users/{id}", get(chat::get_user_route))
        .route("/sync/bootstrap", get(chat::bootstrap))
        .route("/events", get(chat::get_events))
        .route("/conversations", get(chat::list_conversations).post(chat::create_conversation))
        .route("/conversations/dm", post(chat::create_dm))
        .route("/conversations/self", post(chat::create_self))
        .route("/conversations/{id}", get(chat::get_conversation).patch(chat::update_conversation))
        .route("/conversations/{id}/leave", post(chat::leave_conversation))
        .route("/org-settings", get(chat::get_org_settings))
        .route("/admin/org-settings", put(chat::put_org_settings))
        .route("/messages/{id}/hide", post(chat::hide_message))
        .route("/conversations/{id}/messages", get(chat::get_history).post(chat::send_message))
        .route("/conversations/{id}/read", post(chat::mark_read))
        .route("/conversations/{id}/unread", post(chat::mark_unread))
        .route("/messages/{id}", patch(chat::edit_message).delete(chat::delete_message))
        .route("/messages/{id}/reactions/{emoji}", put(chat::add_reaction).delete(chat::remove_reaction))
        .route("/files", post(files::upload))
        .route("/files/{id}", get(files::download))
        .route("/files/{id}/url", get(files::signed_url))
        .route("/files/{id}/meta", put(files::set_meta))
        .route("/files/{id}/thumb", get(files::thumbnail))
        .route("/search", get(search::search))
        .route("/ws", get(ws::ws_handler))
        .route("/me/push", get(crate::push::list).put(crate::push::register))
        .route("/me/push/{id}", delete(crate::push::unregister))
        .route("/admin/updates", get(admin::get_updates))
        .route("/admin/public-url", get(admin::get_public_url).put(admin::put_public_url))
        .route("/admin/push", get(crate::push::get_settings).put(crate::push::put_settings))
        // organisation (phase 2)
        .route("/me/counts", get(org::my_counts))
        .route("/threads", get(org::list_threads))
        .route("/threads/{root}/follow", put(org::follow_thread).delete(org::unfollow_thread))
        .route("/threads/{root}/read", post(org::read_thread))
        .route("/conversations/{id}/threads/{root}", get(org::get_thread))
        .route("/conversations/{id}/pins", get(org::list_pins))
        .route("/conversations/{id}/pins/{mid}", put(org::pin_message).delete(org::unpin_message))
        .route("/conversations/{id}/bookmarks", get(org::list_bookmarks).post(org::add_bookmark))
        .route("/bookmarks/{id}", patch(org::update_bookmark).delete(org::delete_bookmark))
        .route("/groups", get(org::list_groups))
        .route("/admin/groups", post(org::create_group))
        .route("/admin/groups/{id}", patch(org::update_group).delete(org::delete_group))
        .route("/me/prefs", get(org::list_prefs))
        .route("/conversations/{id}/prefs", put(org::set_pref))
        .route("/conversations/order", post(org::order_conversations))
        .route("/sections/order", post(org::order_sections))
        .route("/sections", get(org::list_sections).post(org::create_section))
        .route("/sections/{id}", patch(org::update_section).delete(org::delete_section))
        .route("/drafts", get(org::list_drafts))
        .route("/conversations/{id}/draft", put(org::put_draft))
        .route("/messages/{id}", get(org::get_message))
        .route("/messages/{id}/forward", post(org::forward_message))
        .route("/files", get(org::list_files))
        // membership, saved items, labels, activity
        .route("/conversations/{id}/members", post(social::add_members))
        .route("/conversations/{id}/members/{uid}", delete(social::remove_member))
        .route("/me/avatar-overrides", get(avatars::list_overrides))
        .route("/me/avatar-overrides/{kind}/{target}", put(avatars::set_override).delete(avatars::delete_override))
        .route("/conversations/{id}/avatar", put(avatars::set_conv_avatar))
        .route("/saved", get(social::list_saved))
        .route("/saved/messages", get(social::list_saved_messages))
        .route("/saved/{id}", put(social::save_message).delete(social::unsave_message))
        .route("/saved/{id}/labels", put(social::set_saved_labels))
        .route("/labels", get(social::list_labels).post(social::create_label))
        .route("/labels/{id}", patch(social::update_label).delete(social::delete_label))
        .route("/activity", get(social::activity))
        .route("/activity/read", post(social::read_activity))
        // admin
        .route("/admin/overview", get(admin::overview))
        .route("/admin/users", get(admin::list_users).post(admin::create_user_route))
        .route("/admin/users/{id}", get(admin::get_user_route).patch(admin::update_user).delete(admin::delete_user_route))
        .route("/admin/users/{id}/role", put(admin::set_role))
        .route("/admin/users/{id}/reset-password", post(admin::reset_password))
        .route("/admin/users/{id}/login-link", post(admin::new_login_link))
        .route("/admin/users/{id}/revoke-sessions", post(admin::revoke_user_sessions))
        .route("/admin/users/{id}/clear-history", post(admin::clear_history_route))
        .route("/admin/users/{id}/backup", post(admin::backup_user_route))
        .route("/admin/users/{id}/delete-range", post(admin::delete_range))
        .route("/admin/viewer/conversations", get(adminview::viewer_conversations))
        .route("/admin/viewer/conversations/{id}/messages", get(adminview::viewer_messages))
        .route("/admin/viewer/search", get(adminview::viewer_search))
        .route("/admin/messages/delete", post(adminview::delete_messages))
        .route("/admin/messages/{id}/ts", put(adminview::set_message_ts))
        .route("/admin/restore", post(crate::restore::restore_route))
        .route("/admin/backups", get(admin::list_backups))
        .route("/admin/backups/full", post(crate::fullbackup::backup_now))
        .route("/admin/backups/settings", get(crate::fullbackup::get_backup_settings).put(crate::fullbackup::put_backup_settings))
        .route("/admin/backups/test-target", post(crate::fullbackup::test_backup_target))
        .route("/admin/backups/{id}/download", get(crate::fullbackup::download_backup))
        .route("/restore", post(crate::fullbackup::restore_from_target))
        .route("/restore/upload", post(crate::fullbackup::restore_from_upload).layer(axum::extract::DefaultBodyLimit::disable()))
        .route("/admin/sessions", get(admin::all_sessions))
        .route("/admin/conversations", get(admin::list_conversations))
        .route("/admin/conversations/{id}", delete(admin::delete_conversation))
        .route("/admin/conversations/{id}/members", post(admin::add_members))
        .route("/admin/conversations/{id}/members/{uid}", delete(admin::remove_member))
        .route("/admin/files/{id}", delete(admin::remove_file))
        .route("/admin/storage", get(admin::get_storage).put(admin::put_storage))
        .route("/admin/storage/test", post(admin::test_storage))
        .route("/admin/storage/migrate", post(admin::migrate_storage))
        .route("/admin/storage/verify", post(admin::verify_storage))
        .route("/admin/jobs/{id}", get(admin::job))
        // phase 3: scheduled messages, forms, bot profiles, AI, incoming webhooks
        .route("/scheduled", get(auto::list_scheduled))
        .route("/scheduled/{id}", delete(auto::cancel_scheduled))
        .route("/conversations/{id}/scheduled", post(auto::schedule))
        .route("/messages/{id}/form-response", post(auto::form_response))
        .route("/bots", get(auto::list_bot_profiles))
        .route("/bots/{id}", get(auto::bot_profile))
        .route("/bots/{id}/home/submit", post(auto::home_submit))
        .route("/ai/search", post(auto::ai_search))
        .route("/ai/recap", post(auto::ai_recap))
        .route("/hooks/{id}/{secret}", post(auto::incoming_hook))
        .route("/admin/scheduled", get(botadmin::admin_scheduled))
        .route("/admin/ai", get(botadmin::get_ai))
        .route("/admin/ai/defaults", put(botadmin::put_ai_defaults))
        .route("/admin/ai/providers", post(botadmin::add_ai_provider))
        .route("/admin/ai/providers/{id}", patch(botadmin::update_ai_provider).delete(botadmin::delete_ai_provider))
        .route("/admin/ai/providers/{id}/test", post(botadmin::test_ai_provider))
        .route("/admin/bots", get(botadmin::list_bots).post(botadmin::create_bot))
        .route("/admin/bots/{id}", get(botadmin::get_bot).patch(botadmin::update_bot).delete(botadmin::delete_bot))
        .route("/admin/bots/{id}/token", post(botadmin::regenerate_token))
        .route("/admin/bots/{id}/conversations/{conv}", put(botadmin::add_bot_to_conv).delete(botadmin::remove_bot_from_conv))
        .route("/admin/webhooks", get(botadmin::list_webhooks))
        .route("/admin/webhooks/incoming", post(botadmin::create_incoming))
        .route("/admin/webhooks/incoming/{id}", patch(botadmin::update_incoming).delete(botadmin::delete_incoming))
        .route("/admin/webhooks/outgoing", post(botadmin::create_outgoing))
        .route("/admin/webhooks/outgoing/{id}", patch(botadmin::update_outgoing).delete(botadmin::delete_outgoing))
        .route("/admin/webhooks/outgoing/{id}/test", post(botadmin::test_outgoing))
        // native bot API (bearer bot token)
        .route("/bot/me", get(botapi::me))
        .route("/bot/conversations", get(botapi::conversations))
        .route("/bot/conversations/{id}/messages", get(botapi::history))
        .route("/bot/messages", post(botapi::send))
        .route("/bot/messages/{id}", patch(botapi::edit).delete(botapi::delete))
        .route("/bot/files", post(botapi::upload).layer(axum::extract::DefaultBodyLimit::disable()))
        .route("/bot/files/{id}", get(botapi::download))
        .route("/bot/updates", get(botapi::updates))
        .route("/bot/webhook", get(botapi::get_webhook).put(botapi::put_webhook).delete(botapi::remove_webhook))
        .route("/bot/home", get(botapi::get_home).put(botapi::put_home))
}
