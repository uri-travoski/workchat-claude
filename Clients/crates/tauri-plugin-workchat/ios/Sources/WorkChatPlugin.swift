import ObjectiveC
import SwiftRs
import Tauri
import UIKit
import UserNotifications
import WebKit

/// The iOS side of the WorkChat mobile plugin: notification permission and the APNs device token
/// (`ios_register` answers `{kind: "apns", target: "<hex token>"}`, which the app registers with `PUT /me/push`).
/// Android-only commands answer with an error or a harmless default so the shared Rust code can call them everywhere.
class WorkChatPlugin: Plugin {
  static var token = ""
  static var failure = ""
  static var waiting: [Invoke] = []

  override func load(webview: WKWebView) {
    WorkChatPlugin.installHooks()
  }

  // MARK: APNs token hooks (the app delegate is generated by Tauri, so its methods are added or wrapped at runtime)

  static func installHooks() {
    DispatchQueue.main.async {
      guard let delegate = UIApplication.shared.delegate else { return }
      let cls: AnyClass = type(of: delegate)

      let okSel = #selector(UIApplicationDelegate.application(_:didRegisterForRemoteNotificationsWithDeviceToken:))
      let okBlock: @convention(block) (AnyObject, UIApplication, Data) -> Void = { _, _, data in
        WorkChatPlugin.gotToken(data)
      }
      if !class_addMethod(cls, okSel, imp_implementationWithBlock(okBlock), "v@:@@"), let m = class_getInstanceMethod(cls, okSel) {
        let orig = method_getImplementation(m)
        typealias F = @convention(c) (AnyObject, Selector, UIApplication, Data) -> Void
        let wrapped: @convention(block) (AnyObject, UIApplication, Data) -> Void = { s, app, data in
          unsafeBitCast(orig, to: F.self)(s, okSel, app, data)
          WorkChatPlugin.gotToken(data)
        }
        method_setImplementation(m, imp_implementationWithBlock(wrapped))
      }

      let failSel = #selector(UIApplicationDelegate.application(_:didFailToRegisterForRemoteNotificationsWithError:))
      let failBlock: @convention(block) (AnyObject, UIApplication, Error) -> Void = { _, _, err in
        WorkChatPlugin.gotFailure(err)
      }
      if !class_addMethod(cls, failSel, imp_implementationWithBlock(failBlock), "v@:@@"), let m = class_getInstanceMethod(cls, failSel) {
        let orig = method_getImplementation(m)
        typealias F = @convention(c) (AnyObject, Selector, UIApplication, Error) -> Void
        let wrapped: @convention(block) (AnyObject, UIApplication, Error) -> Void = { s, app, err in
          unsafeBitCast(orig, to: F.self)(s, failSel, app, err)
          WorkChatPlugin.gotFailure(err)
        }
        method_setImplementation(m, imp_implementationWithBlock(wrapped))
      }
    }
  }

  static func gotToken(_ data: Data) {
    token = data.map { String(format: "%02x", $0) }.joined()
    failure = ""
    let list = waiting
    waiting = []
    for i in list { i.resolve(["kind": "apns", "target": token]) }
  }

  static func gotFailure(_ err: Error) {
    failure = err.localizedDescription
    let list = waiting
    waiting = []
    for i in list { i.reject("Apple push registration failed: \(failure)") }
  }

  // MARK: commands

  private func permission(_ done: @escaping (String) -> Void) {
    UNUserNotificationCenter.current().getNotificationSettings { s in
      switch s.authorizationStatus {
      case .authorized, .provisional, .ephemeral: done("granted")
      case .denied: done("denied")
      default: done("prompt")
      }
    }
  }

  @objc func status(_ invoke: Invoke) {
    permission { state in
      invoke.resolve([
        "notifications": state,
        "distributors": [String](),
        "distributor": "",
        "fcm": false,
        "keepAlive": false,
        "canInstall": false,
        "endpoint": WorkChatPlugin.token,
        "pushError": WorkChatPlugin.failure,
      ])
    }
  }

  @objc func request_permission(_ invoke: Invoke) {
    UNUserNotificationCenter.current().requestAuthorization(options: [.alert, .sound, .badge]) { granted, _ in
      invoke.resolve(["state": granted ? "granted" : "denied"])
    }
  }

  @objc func ios_register(_ invoke: Invoke) {
    UNUserNotificationCenter.current().requestAuthorization(options: [.alert, .sound, .badge]) { granted, _ in
      DispatchQueue.main.async {
        if !granted {
          invoke.reject("Notifications are turned off for WorkChat. Allow them in the Settings app.")
          return
        }
        if !WorkChatPlugin.token.isEmpty {
          invoke.resolve(["kind": "apns", "target": WorkChatPlugin.token])
          return
        }
        WorkChatPlugin.waiting.append(invoke)
        UIApplication.shared.registerForRemoteNotifications()
        // No answer in 15 seconds (no network, or a build without the push entitlement).
        DispatchQueue.main.asyncAfter(deadline: .now() + 15) {
          if let i = WorkChatPlugin.waiting.firstIndex(where: { $0 === invoke }) {
            WorkChatPlugin.waiting.remove(at: i)
            invoke.reject("Apple did not return a push token. This build may not be signed with push notifications.")
          }
        }
      }
    }
  }

  @objc func push_unregister(_ invoke: Invoke) {
    DispatchQueue.main.async {
      UIApplication.shared.unregisterForRemoteNotifications()
      WorkChatPlugin.token = ""
      invoke.resolve()
    }
  }

  @objc func set_keep_alive(_ invoke: Invoke) { invoke.resolve(["running": false]) }
  @objc func set_system_bars(_ invoke: Invoke) { invoke.resolve() }
  @objc func install_apk(_ invoke: Invoke) { invoke.reject("Not available on iOS.") }
  @objc func save_download(_ invoke: Invoke) { invoke.reject("Not available on iOS.") }
  @objc func view_file(_ invoke: Invoke) { invoke.reject("Not available on iOS.") }
  @objc func pick_files(_ invoke: Invoke) { invoke.reject("Not available on iOS.") }
}

@_cdecl("init_plugin_workchat")
func initPlugin() -> Plugin {
  return WorkChatPlugin()
}
